#!/usr/bin/env python3
"""Generate miyoo/src/font_data.h from Terminus console fonts (SIL OFL 1.1).

Extracts printable ASCII (32..126) using each PSF's unicode table, so glyph
order in the console font does not matter. Run from the repo root:

    python3 tools/gen_font.py > miyoo/src/font_data.h
"""
import gzip
import struct
import sys

FONTS = [
    ("font_body", "/usr/share/consolefonts/Lat15-TerminusBold20x10.psf.gz"),
    ("font_big", "/usr/share/consolefonts/Lat15-TerminusBold32x16.psf.gz"),
]


def load_psf(path):
    data = gzip.open(path).read()
    if data[:4] == b"\x72\xb5\x4a\x86":
        _, _, hdr, flags, count, size, height, width = struct.unpack("<8I", data[:32])
        glyphs = [data[hdr + i * size: hdr + (i + 1) * size] for i in range(count)]
        table = data[hdr + count * size:]
        cmap = {}
        if flags & 1:
            for idx, entry in enumerate(table.split(b"\xff")[:count]):
                seqs = entry.split(b"\xfe")[0].decode("utf-8", "replace")
                for ch in seqs:
                    cmap.setdefault(ord(ch), idx)
        return width, height, glyphs, cmap
    if data[:2] == b"\x36\x04":
        mode, height = data[2], data[3]
        count = 512 if mode & 1 else 256
        glyphs = [data[4 + i * height: 4 + (i + 1) * height] for i in range(count)]
        table = data[4 + count * height:]
        cmap = {}
        if mode & 2:
            idx = 0
            for i in range(0, len(table) - 1, 2):
                (u,) = struct.unpack("<H", table[i:i + 2])
                if u == 0xFFFF:
                    idx += 1
                elif u != 0xFFFE:
                    cmap.setdefault(u, idx)
        return 8, height, glyphs, cmap
    raise SystemExit(f"{path}: not a PSF font")


def main():
    out = sys.stdout
    out.write("/* Generated by tools/gen_font.py from Terminus Font (SIL OFL 1.1,\n")
    out.write(" * Copyright (c) Dimitar Toshkov Zhekov). Printable ASCII only. */\n")
    out.write("#pragma once\n#include <stdint.h>\n\n")
    for name, path in FONTS:
        width, height, glyphs, cmap = load_psf(path)
        row_bytes = (width + 7) // 8
        out.write(f"#define {name.upper()}_W {width}\n#define {name.upper()}_H {height}\n")
        out.write(f"/* {path.rsplit('/', 1)[-1]}: 95 glyphs x {height} rows, MSB-first, {row_bytes} byte(s)/row */\n")
        ctype = "uint8_t" if row_bytes == 1 else "uint16_t"
        out.write(f"static const {ctype} {name}_bits[95][{height}] = {{\n")
        for code in range(32, 127):
            glyph = glyphs[cmap.get(code, cmap.get(ord("?")))]
            rows = []
            for r in range(height):
                chunk = glyph[r * row_bytes:(r + 1) * row_bytes]
                rows.append(int.from_bytes(chunk, "big"))
            fmt = "0x%02x" if row_bytes == 1 else "0x%04x"
            out.write("  {" + ",".join(fmt % v for v in rows) + "},\n")
        out.write("};\n\n")


if __name__ == "__main__":
    main()
